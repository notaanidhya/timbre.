defmodule TimbreWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :timbre

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  @session_options [
    store: :cookie,
    key: "_timbre_key",
    signing_salt: "7vtBnyG/",
    same_site: "Lax"
  ]

  socket "/socket", TimbreWeb.UserSocket,
    websocket: [connect_info: [session: @session_options]],
    longpoll: false

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :timbre,
    gzip: not code_reloading?,
    only: TimbreWeb.static_paths(),
    raise_on_missing_only: code_reloading?

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :timbre
  end

  plug Plug.RequestId
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]
  plug :cors_headers

  plug Plug.Parsers,
    parsers: [:urlencoded, :multipart, :json],
    pass: ["*/*"],
    json_decoder: Phoenix.json_library(),
    length: 200_000_000

  plug Plug.MethodOverride
  plug Plug.Head
  plug Plug.Session, @session_options
  plug TimbreWeb.Router

  defp cors_headers(conn, _opts) do
    origin = Plug.Conn.get_req_header(conn, "origin") |> List.first() || "*"

    conn =
      conn
      |> Plug.Conn.put_resp_header("access-control-allow-origin", origin)
      |> Plug.Conn.put_resp_header("access-control-allow-methods", "GET, POST, PUT, DELETE, OPTIONS")
      |> Plug.Conn.put_resp_header("access-control-allow-headers", "content-type, authorization, accept, origin, x-client-id")
      |> Plug.Conn.put_resp_header("access-control-allow-credentials", "true")

    if conn.method == "OPTIONS" do
      conn |> Plug.Conn.send_resp(204, "") |> Plug.Conn.halt()
    else
      conn
    end
  end
end
